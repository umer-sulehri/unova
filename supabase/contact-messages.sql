-- ============================================================
-- Contact form inbox for the admin dashboard
-- Run this once in the Supabase SQL Editor if your database was
-- created before contact messages were added.
-- ============================================================

create table if not exists contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text not null default '',
  subject text not null default '',
  budget text not null default '',
  message text not null,
  status text not null default 'new' check (status in ('new', 'read')),
  created_at timestamptz not null default now()
);

create index if not exists contact_messages_created_at_idx
  on contact_messages (created_at desc);

create index if not exists contact_messages_status_idx
  on contact_messages (status);

-- Access goes through the Next.js server with the service role key.
alter table contact_messages enable row level security;
